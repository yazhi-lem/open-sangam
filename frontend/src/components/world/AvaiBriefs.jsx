import { useState } from 'react'
import { ChevronDown, FileText, Quote } from 'lucide-react'
import { AVAI_RESEARCH_BRIEFS } from '../../data/library'
import useAppStore from '../../store/useAppStore'
import Badge from '../ui/Badge'
import Card from '../ui/Card'
import Markdown from '../ui/Markdown'

export default function AvaiBriefs() {
  const language = useAppStore((s) => s.language)
  const [openId, setOpenId] = useState(null)
  const L = (ta, en) => (language === 'ta' ? ta : en)

  return (
    <section id="avai-briefs" className="mt-12 border-t border-line-strong pt-8">
      <div className="mb-4 flex flex-wrap items-end justify-between gap-3 border-b border-line-strong pb-2">
        <div>
          <h2 className={`text-2xl font-bold text-primary ${language === 'ta' ? 'tamil' : ''}`}>
            {L('அவை ஆய்வுக் குறிப்புகள்', 'Avai research briefs')}
          </h2>
          <p className="text-sm text-muted">
            {L('உள்ளூர் அவைப் புலவர்கள் உருவாக்கிய ஆய்வுக் குறிப்புகள்.', 'Research briefs generated by the local Avai agents.')}
          </p>
        </div>
        <Badge variant="accent" size="sm">{AVAI_RESEARCH_BRIEFS.length} briefs</Badge>
      </div>

      <div className="space-y-2">
        {AVAI_RESEARCH_BRIEFS.map((brief) => (
          <Card key={brief.id} variant="flat" className="p-3">
            <button
              type="button"
              onClick={() => setOpenId(openId === brief.id ? null : brief.id)}
              className="flex w-full items-start justify-between gap-3 text-left"
            >
              <div className="min-w-0">
                <p className={`text-sm font-bold text-primary ${language === 'ta' ? 'tamil' : ''}`}>
                  {L(brief.titleTa, brief.titleEn)}
                </p>
                <p className="mt-0.5 flex flex-wrap items-center gap-2 text-[10px] text-faint">
                  <span className="font-mono">{brief.agent}</span>
                  <span>·</span>
                  <span>{brief.citationCount} {L('சான்றுகள்', 'citations')}</span>
                  <span>·</span>
                  <span>{brief.evidenceStatus}</span>
                </p>
              </div>
              <ChevronDown size={16} className={`shrink-0 text-faint transition-transform ${openId === brief.id ? 'rotate-180' : ''}`} />
            </button>
            {openId === brief.id && (
              <div className="mt-3 border-t border-line/60 pt-3">
                <div className="max-h-96 overflow-y-auto rounded-lg border border-line bg-surface-alt/40 p-3">
                  <Markdown text={brief.responseText} className="text-[12px]" />
                </div>
                <a
                  href={`https://github.com/yazhi-lem/open-sangam/blob/main/data/library/avai-research/${brief.file}`}
                  className="mt-2 inline-flex items-center gap-1 text-[10px] font-semibold text-accent hover:underline"
                  target="_blank"
                  rel="noreferrer"
                >
                  <FileText size={11} /> {L('முழு ஆய்வுக் குறிப்பு', 'Full brief')}
                </a>
              </div>
            )}
          </Card>
        ))}
      </div>
      <p className="mt-3 flex items-center gap-1 text-[10px] text-faint">
        <Quote size={11} /> {L('இவை ஆய்வுத் தொடக்கங்கள்; அறிஞர் சரிபார்ப்பு தேவை.', 'These are research leads; scholar review is required.')}
      </p>
    </section>
  )
}
